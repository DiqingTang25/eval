def main():
    total = len(ADVERSARIAL_QAS)
    oos = sum(1 for _, t, _, _ in ADVERSARIAL_QAS if t == "越界测试")
    mis = sum(1 for _, t, _, _ in ADVERSARIAL_QAS if t == "诱导测试")
    edge = sum(1 for _, t, _, _ in ADVERSARIAL_QAS if t == "边界测试")
    print(f"Generated {total} adversarial QAs: {oos} OOS + {mis} MIS + {edge} EDGE")

    # Load existing bank
    with open(BANK_FILE, 'r', encoding='utf-8') as f:
        bank = json.load(f)

    items = bank if isinstance(bank, list) else bank.get('items', [])

    # Remove old adversarial QAs (keep normal QAs)
    normal = [q for q in items if q.get('type') not in ('越界测试', '诱导测试', '边界测试')]
    print(f"Kept {len(normal)} normal QAs")

    # Add all new adversarial QAs
    new_items = []
    for qa_id, qtype, question, rubric in ADVERSARIAL_QAS:
        new_items.append({
            "qa_id": qa_id,
            "phase": "ALL",
            "type": qtype,
            "difficulty": "困难",
            "question": question,
            "golden_answer": f"【{qtype}-评分标准】\n{rubric}",
        })

    all_items = normal + new_items

    if isinstance(bank, dict):
        bank['items'] = all_items
        bank['_updated'] = '2026-07-16: 60 adversarial QAs generated'
    else:
        bank = all_items

    with open(BANK_FILE, 'w', encoding='utf-8') as f:
        json.dump(bank, f, ensure_ascii=False, indent=2)

    print(f"Saved {len(all_items)} total QAs ({len(normal)} normal + {len(new_items)} adversarial)")

if __name__ == '__main__':
    main()
